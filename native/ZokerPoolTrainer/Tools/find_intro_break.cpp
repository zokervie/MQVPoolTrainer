// 0.44.1 M5: choose the intro's real 9-ball break once, offline. Builds Rules(NineBall).rack(seed), scans cue-ball
// position / aim / speed with Physics.cpp, keeps a break that drops a ball in a CORNER pocket between 0.6 and 1.5 s
// after the strike (intro timeline: strike at 1.6 s + 0.375 s of slow-motion ⇒ the drop lands 2.6–3.5 s, inside the
// 2.2–3.6 s "follow the falling ball" window) with the cue ball staying on the table. Prints BankLab/UI/IntroBreak.h.
// Build: xcrun clang++ -std=c++17 -O2 -IBankLab/Core Tools/find_intro_break.cpp BankLab/Core/Physics.cpp BankLab/Core/ElevatedPhysics.cpp
#include "Physics.hpp"
#include "MatchRules.hpp"
#include <cmath>
#include <cstdio>
using namespace banklab;
using banklab::match::Rules;using banklab::match::Discipline;
int main(){
    const std::uint64_t seed=20261117;
    Rules rules(Discipline::NineBall);
    for(double cx:{0.0,-0.18,0.18,-0.30,0.30})for(double speed:{8.0,8.5,9.0,7.5})for(int ai=-6;ai<=6;++ai)for(double top:{0.0,-0.2,0.2}){
        auto balls=rules.rack(seed);balls[0].p={cx,-0.90};
        V2 head{};for(auto&b:balls)if(b.id==1)head=b.p;
        const double angle=std::atan2(head.y-balls[0].p.y,head.x-balls[0].p.x)+ai*0.0015;
        World w;w.reset(balls);w.strike(angle,speed,0,top);
        for(int n=0;n<960*20&&w.moving();++n)w.step();
        const Event* first=nullptr;bool scratch=false;
        for(auto&e:w.events)if(e.kind==2){if(e.a==0)scratch=true;else if(!first)first=&e;}
        if(!first||scratch)continue;
        const bool corner=first->b==0||first->b==1||first->b==4||first->b==5;
        if(!corner||first->time<0.6||first->time>1.5)continue;
        std::printf("/* Generated by Tools/find_intro_break.cpp — do not edit by hand. */\n#ifndef BL_INTRO_BREAK_H\n#define BL_INTRO_BREAK_H\n");
        std::printf("/* 0.44.1 M5 intro break: Rules(NineBall).rack(%llu), cue ball moved to x = %.2f. Replayed live by the intro and\n   re-simulated by Tests/IntroBreakTests.cpp, which must reproduce every pocket event below (ball, pocket, time ±1 ms). */\n",(unsigned long long)seed,cx);
        std::printf("#define BL_INTRO_RACK_SEED %lluULL\n#define BL_INTRO_CUE_X %.17g\n#define BL_INTRO_CUE_Y %.17g\n#define BL_INTRO_ANGLE %.17g\n#define BL_INTRO_SPEED %.17g\n#define BL_INTRO_TOP %.17g\n",(unsigned long long)seed,cx,-0.90,angle,speed,top);
        std::printf("#define BL_INTRO_BALL_COUNT %d\n/* id, x, y (metres, table frame) — the exact start state, cue ball first. */\nstatic const double BLIntroBalls[%d][3] = {",(int)balls.size(),(int)balls.size());
        for(auto&q:balls)std::printf("{%d,%.17g,%.17g},",q.id,q.p.x,q.p.y);
        std::printf("};\n");
        int count=0;for(auto&e:w.events)if(e.kind==2)++count;
        std::printf("#define BL_INTRO_POT_COUNT %d\nstatic const int BLIntroPotBall[%d] = {",count,count);
        for(auto&e:w.events)if(e.kind==2)std::printf("%d,",e.a);
        std::printf("};\nstatic const int BLIntroPotPocket[%d] = {",count);
        for(auto&e:w.events)if(e.kind==2)std::printf("%d,",e.b);
        std::printf("};\nstatic const double BLIntroPotTime[%d] = {",count);
        for(auto&e:w.events)if(e.kind==2)std::printf("%.9f,",e.time);
        std::printf("};\n/* First corner drop: ball %d, pocket %d, %.3f s after the strike. */\n#define BL_INTRO_FIRST_DROP_TIME %.9f\n#define BL_INTRO_FIRST_DROP_BALL %d\n#endif\n",first->a,first->b,first->time,first->time,first->a);
        return 0;
    }
    std::fprintf(stderr,"no break found\n");return 1;
}
